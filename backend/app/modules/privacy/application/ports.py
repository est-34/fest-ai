from __future__ import annotations

from typing import Any, Protocol

from app.shared.application.ports import UnitOfWork as SharedUnitOfWork


class PrivacyRepository(Protocol):
    def ai_logs_for_visitor(self, visitor_id) -> list[dict]: ...
    def expired_ai_logs(self) -> list[dict]: ...
    def expired_survey_responses(self) -> list[dict]: ...
    def purge_sessions_visitor_sessions(
        self, *, visitor_id=None, expired_days=None
    ) -> list[dict]: ...
    def _children_pg_constraint(self, params: Any = ()) -> Any: ...
    def _has_id_information_schema(self, params: Any = ()) -> Any: ...
    def delete_rows_query(
        self, params: Any = (), *, child_table: Any, column: Any
    ) -> Any: ...
    def delete_rows_query_2(
        self, params: Any = (), *, child_table: Any, column: Any
    ) -> Any: ...
    def delete_rows_query_3(self, params: Any = (), *, table: Any) -> int: ...
    def purge_sessions_query(self, params: Any = (), *, table: Any) -> Any: ...
    def purge_personal_data_business_events(self, params: Any = ()) -> int: ...
    def purge_personal_data_business_recommendation_events(
        self, params: Any = ()
    ) -> int: ...
    def purge_personal_data_users(self, params: Any = ()) -> int: ...
    def record_identity_visitor_identity_events(self, params: Any = ()) -> Any: ...
    def record_identity_visitor_identity_events_2(self, params: Any = ()) -> Any: ...


class UnitOfWork(SharedUnitOfWork, Protocol):
    privacy: PrivacyRepository
