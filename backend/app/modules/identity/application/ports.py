from __future__ import annotations

from typing import Any, Protocol

from app.shared.application.ports import UnitOfWork as SharedUnitOfWork


class AuthRepository(Protocol):
    def issue_refresh_token_insert_refresh_tokens(self, params: Any = ()) -> Any: ...
    def lock_state_select_login_attempts(self, params: Any = ()) -> Any: ...
    def record_failure_update_login_attempts(self, params: Any = ()) -> Any: ...
    def record_failure_update_login_attempts_2(self, params: Any = ()) -> Any: ...
    def login_select_users(self, params: Any = ()) -> Any: ...
    def login_execute_login_attempts(self, params: Any = ()) -> Any: ...
    def refresh_select_refresh_tokens(self, params: Any = ()) -> Any: ...
    def refresh_select_refresh_tokens_2(self, params: Any = ()) -> Any: ...
    def revoke_refresh_tokens(self, params: Any = ()) -> Any: ...
    def refresh_update_refresh_tokens_2(self, params: Any = ()) -> Any: ...
    def logout_update_refresh_tokens(self, params: Any = ()) -> Any: ...
    def valid_invitation_select_OF(self, params: Any = (), *, lock: Any) -> Any: ...
    def lookup_invitation_select_users(self, params: Any = ()) -> Any: ...
    def accept_invitation_select_users(self, params: Any = ()) -> Any: ...
    def accept_invitation_select_memberships(self, params: Any = ()) -> Any: ...
    def accept_invitation_insert_users_2(self, params: Any = ()) -> Any: ...
    def accept_invitation_insert_memberships_2(self, params: Any = ()) -> Any: ...
    def accept_invitation_update_memberships(self, params: Any = ()) -> Any: ...
    def accept_invitation_update_festival_businesses(self, params: Any = ()) -> Any: ...
    def accept_invitation_update_merchant_invitations(
        self, params: Any = ()
    ) -> Any: ...
    def change_password_select_users(self, params: Any = ()) -> Any: ...
    def change_password_update_users(self, params: Any = ()) -> Any: ...


class UnitOfWork(SharedUnitOfWork, Protocol):
    auth: AuthRepository
